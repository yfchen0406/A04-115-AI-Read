function inspect(collection,expectedType){
  assert.equal(collection.type,'FeatureCollection');
  assert.ok(collection.features.length>0);
  for(const feature of collection.features){
    const p=feature.properties;
    for(const key of ['id','name','region','polity','start_year','end_year','control_type','confidence','source_id','notes']) assert.ok(p[key]!==undefined,`${p.id} has ${key}`);
    assert.ok(Number.isInteger(p.start_year)&&Number.isInteger(p.end_year));
    assert.ok(p.start_year>=1661&&p.end_year<=1799&&p.start_year<=p.end_year,`${p.id} uses the documented period`);
    assert.ok(['high','medium','low'].includes(p.confidence));
    assert.ok(sourceIds.has(p.source_id),`${p.id} has a registered source`);
    assert.ok(Array.isArray(expectedType)?expectedType.includes(feature.geometry.type):feature.geometry.type===expectedType);
    const points=feature.geometry.type==='Point'?[feature.geometry.coordinates]:feature.geometry.type==='LineString'?feature.geometry.coordinates:feature.geometry.type==='Polygon'?feature.geometry.coordinates.flat(1):feature.geometry.type==='MultiPolygon'?feature.geometry.coordinates.flat(2):feature.geometry.coordinates.flat(1);
    for(const [lon,lat] of points){assert.ok(Number.isFinite(lon)&&lon>=-180&&lon<=180);assert.ok(Number.isFinite(lat)&&lat>=-90&&lat<=90);}
    if(collection!==polities&&p.routeType!=='trade'&&/歐洲|北歐|東歐/.test(p.region||'')) for(const [lon,lat] of points) assert.ok(lon>=-15&&lon<=45&&lat>=35&&lat<=72,`${p.id} coordinates must fall within its stated European region in longitude/latitude order`);
    if(p.routeType==='military'&&/清朝|清俄邊境|蒙古與西北|四川西部|雲南—緬甸|廣西—北越/.test(p.region||'')) for(const [lon,lat] of points) assert.ok(lon>=75&&lon<=135&&lat>=10&&lat<=60,`${p.id} coordinates must fall within its stated Qing-era Asian theater`);
    if(p.routeType==='military'&&/北美/.test(p.region||'')) for(const [lon,lat] of points) assert.ok(lon>=-130&&lon<=-50&&lat>=20&&lat<=70,`${p.id} coordinates must fall within its stated North American theater`);
    if(p.id==='trade-canton-macau') for(const [lon,lat] of points) assert.ok(lon>=105&&lon<=125&&lat>=15&&lat<=30,'Canton route stays in the Pearl River delta');
    if(p.id==='trade-indian-ocean') for(const [lon,lat] of points) assert.ok(lon>=30&&lon<=130&&lat>=-40&&lat<=35,'Indian Ocean route stays in its named ocean region');
  }
}
