'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');

const root = path.join(__dirname, '..');
const html = fs.readFileSync(path.join(root, 'index.html'), 'utf8');
const css = fs.readFileSync(path.join(root, 'css/historical-map.css'), 'utf8');
const historyModule = fs.readFileSync(path.join(root, 'js/historical-events.js'), 'utf8');
const mapModule = fs.readFileSync(path.join(root, 'js/historical-map.js'), 'utf8');
const mapLoader = fs.readFileSync(path.join(root, 'js/historical-map-loader.js'), 'utf8');
const launcher = fs.readFileSync(path.join(root, 'start-local-site.cmd'), 'utf8');
const guide = fs.readFileSync(path.join(root, 'docs/static-site-run.md'), 'utf8');
const quickStart = fs.readFileSync(path.join(root, 'README-先看這裡.txt'), 'utf8');
const sources = JSON.parse(fs.readFileSync(path.join(root, 'data/historical-map-sources.json'), 'utf8'));

assert.match(html, /id="local-run-notice"[^>]*hidden/, 'local file protocol notice is present and initially hidden');
assert.match(html, /location\.protocol==="file:"/, 'notice activates for file URLs');
assert.match(html, /start-local-site\.cmd/, 'notice directs users to the local server launcher');
assert.match(html, /href="#historical-map"[^>]*>前往第四階段完整互動地圖/, 'phase three has a visible link to the full phase-four map');
assert.match(html, /id="global-history-map-preview"[^>]*class="historical-map-canvas"/, 'phase three includes an interactive historical-map preview');
assert.match(html, /data-map-preview-year/, 'phase-three map preview presents the shared year');
assert.match(html, /可點擊底圖國名或使用上方國家選單/, 'map announces direct country selection and the synchronized selector');
assert.match(historyModule, /file:\/\/[^']*start-local-site\.cmd/, 'timeline failure names the file protocol and local launcher');
assert.match(mapModule, /file:\/\/ 開啟[^']*start-local-site\.cmd/, 'map failure names the file protocol and local launcher');
assert.match(html, /historical-map-loader\.js" defer><\/script><script src="\.\/js\/historical-map\.js/, 'map loader is initialized before the map module');
assert.match(mapModule, /HistoricalMapLibraryLoader\.loadResources/, 'map module uses resilient resource loading');
assert.match(mapModule, /dataLoadWarnings\.join\(' '\)/, 'map displays the exact partial resource failures');
assert.match(mapLoader, /cdn\.jsdelivr\.net\/npm\/maplibre-gl@6\.16\.0/,'MapLibre primary CDN is version-pinned');
assert.match(mapLoader, /unpkg\.com\/maplibre-gl@6\.16\.0/,'MapLibre has a pinned backup CDN');
assert.match(css, /\.local-run-notice\[hidden\]\{display:none\}/, 'hidden notice stays hidden until required');
assert.match(launcher, /http\.server %PORT% --bind 127\.0\.0\.1/, 'Windows launcher serves the site over local HTTP');
assert.match(launcher, /http:\/\/127\.0\.0\.1:%PORT%\//, 'Windows launcher opens the local site URL');
assert.match(guide, /不要直接雙擊 `index\.html`/, 'local run guide explains the file protocol limitation');
assert.match(quickStart, /雙擊「start-local-site\.cmd」/, 'root quick-start tells users exactly which file to open');
assert.match(quickStart, /請勿直接雙擊 index\.html/, 'root quick-start distinguishes the launcher from the page');
assert.match(quickStart, /左右雙地圖比較.*共用年份和國家篩選/, 'root quick-start explains how the paired maps synchronize');
assert.match(quickStart, /清朝覆蓋不完整.*缺少蘇格蘭.*十三殖民地/, 'root quick-start discloses historical coverage limits');
assert.ok(fs.existsSync(path.join(root, 'data/historical-map-index.json')), 'relative map data is packaged beside the site');
const openFreeMap = sources.sources.find(source => source.id === 'openfreemap');
assert.match(openFreeMap.license, /no stated per-view\/request cap/i, 'OpenFreeMap usage cap status is recorded');
assert.match(openFreeMap.license, /without availability/i, 'OpenFreeMap availability disclaimer is recorded');
assert.match(openFreeMap.use, /3,000 tiles 或 50 MB/, 'OpenFreeMap offline download terms are recorded');
console.log('PASS static run entry: file protocol notice, phase-three map link, local HTTP launcher, source assets, and current OpenFreeMap service terms.');
